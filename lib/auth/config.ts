import {
  googleProvider,
  jwtCallback,
  sessionCallback,
  signInCallback,
  redirectCallback,
} from "./providers";

/**
 * NextAuth Configuration for SellFlow-Saas
 * Supports:
 * - Google OAuth
 * - Credentials (optional)
 * - Supabase integration via Prisma
 * - JWT-based sessions
 * - CSRF protection (built-in)
 */
export const authOptions = {
  providers: [googleProvider],

  pages: {
    signIn: "/auth/signin",
  },

  callbacks: {
    async jwt(params: any) {
      return jwtCallback(params);
    },

    async session(params: any) {
      return sessionCallback(params);
    },

    async signIn(params: any) {
      return signInCallback(params);
    },

    async redirect(params: any) {
      return redirectCallback(params);
    },
  },

  session: {
    strategy: "jwt" as const,
  },
};

/**
 * Environment Variables Required:
 *
 * 1. NextAuth Core:
 *    - NEXTAUTH_SECRET: Generated by: openssl rand -base64 32
 *    - NEXTAUTH_URL: http://localhost:3000 (dev) or https://yourdomain.com (prod)
 *
 * 2. Google OAuth:
 *    - GOOGLE_CLIENT_ID: From Google Cloud Console
 *    - GOOGLE_CLIENT_SECRET: From Google Cloud Console
 *
 * 3. Database (Prisma + Supabase):
 *    - DATABASE_URL: postgresql://user:password@host/database
 *
 * 4. Optional:
 *    - NODE_ENV: development | production
 *
 * Example .env.local:
 * ---
 * NEXTAUTH_SECRET=your-secret-here
 * NEXTAUTH_URL=http://localhost:3000
 * GOOGLE_CLIENT_ID=xxx.apps.googleusercontent.com
 * GOOGLE_CLIENT_SECRET=xxx
 * DATABASE_URL=postgresql://user:password@db.supabase.co:5432/postgres
 * NODE_ENV=development
 * ---
 */
